    function parsePrayerTimes(timesArray) {
        const rows = new Map();
        if (!Array.isArray(timesArray)) return rows;

        timesArray.forEach((line) => {
            if (typeof line !== "string") return;
            const cleanLine = line.replace(/["']/g, "").trim();
            const parts = cleanLine.split("~~~~~");
            if (parts.length === 2) {
                const dateKey = parts[0].trim();
                const times = parts[1].split("|").map((t) => t.trim());
                if (dateKey.match(/^\d{2}-\d{2}$/) && times.length === 6) {
                    rows.set(dateKey, times);
                }
            }
        });
        return rows;
    }

