        if (mosqueTrigger) {
            e.preventDefault();
            e.stopPropagation();
            toggleStylesheet();
            return;
        }

        // 3. النقر على اسم الفجر ينقل للون الثيم التالي
        const fajrNameTrigger = target.closest("[data-key='fajr'] .s4-card-name, .fajr-card strong");
        if (fajrNameTrigger) {
            e.preventDefault();
            e.stopPropagation();
            cycleThemeNext(true);
            return;
        }

        // 4. النقر على وقت صلاة الفجر يعود للون الثيم السابق
