    function renderSettingsModal() {
        if (!settingsPrayersContainer) return;
        const activeElem = document.activeElement;
        const activeKey = activeElem ? activeElem.getAttribute("data-key") : null;
        const activeAction = activeElem ? activeElem.getAttribute("data-action") : null;
        const activeId = activeElem ? activeElem.id : null;

        settingsPrayersContainer.innerHTML = "";
        const now = new Date();
        const prayers = makePrayerList(now, settings.prayerOffsets);

        prayers.forEach((p) => {
            const offsetVal = settings.prayerOffsets[p.key] || 0;
            const offsetStr = (offsetVal > 0 ? "+" : "") + offsetVal + " دقيقة";
            const iqamaVal = settings.iqamaDelays[p.key] || 0;
            const iqamaStr = iqamaVal + " دقيقة";

            const row = document.createElement("div");
            row.className = "settings-row";
            row.innerHTML = `
                <div>
                    <strong>${p.name}</strong>
                    <small>الوقت المعدل: ${formatDisplayTime(p.time)}</small>
                </div>
                <div class="prayer-controls">
                    <label class="control-field">
                        <span>تعديل الوقت (الأذان)</span>
                        <div class="minute-control">
                            <button type="button" data-action="offset-dec" data-key="${p.key}">−</button>
                            <span class="minute-display">${offsetStr}</span>
                            <button type="button" data-action="offset-inc" data-key="${p.key}">+</button>
                        </div>
                    </label>
                    <label class="control-field">
                        <span>الإقامة</span>
                        <div class="minute-control">
                            <button type="button" data-action="iqama-dec" data-key="${p.key}">−</button>
                            <span class="minute-display">${iqamaStr}</span>
                            <button type="button" data-action="iqama-inc" data-key="${p.key}">+</button>
                        </div>
                    </label>
                </div>
            `;
            settingsPrayersContainer.appendChild(row);
        });

        const hijriDisplay = document.getElementById("hijri-display");
        if (hijriDisplay) {
            const hVal = settings.hijriOffset || 0;
            hijriDisplay.textContent = (hVal > 0 ? "+" : "") + hVal + " يوم";
        }
        if (mosqueNameInput) mosqueNameInput.value = settings.mosqueName || "مسجد النور";

        const sheetSelect = document.getElementById("stylesheet-select");
        if (sheetSelect) {
            sheetSelect.value = currentStylesheet;
        }

        const citySelect = document.getElementById("city-select");
        if (citySelect) {
            if (citySelect.options.length <= 1 && window.IRAQ_CITIES_INDEX && window.IRAQ_CITIES_INDEX.length > 0) {
                citySelect.innerHTML = "";
                window.IRAQ_CITIES_INDEX.forEach((c) => {
                    const opt = document.createElement("option");
                    opt.value = c.id;
                    opt.textContent = `${c.name} (${c.en})`;
                    citySelect.appendChild(opt);
                });
            }
            citySelect.value = currentCityId;
        }

        if (activeKey && activeAction) {
            const targetBtn = settingsPrayersContainer.querySelector(`button[data-key="${activeKey}"][data-action="${activeAction}"]`);
            if (targetBtn) targetBtn.focus();
        } else if (activeId) {
            const targetEl = document.getElementById(activeId);
            if (targetEl) targetEl.focus();
        }
    }

    let modalOpenedAt = 0;

    function openSettingsModal() {
        if (!settingsModal) return;
        modalOpenedAt = Date.now();
        try {
            renderSettingsModal();
        } catch (err) {
            console.error("خطأ أثناء تجهيز نافذة الإعدادات:", err);
        }
        settingsModal.classList.add("is-open");
        settingsModal.style.setProperty("display", "flex", "important");
        settingsModal.style.setProperty("visibility", "visible", "important");
        settingsModal.style.setProperty("opacity", "1", "important");
        settingsModal.style.setProperty("z-index", "9999999", "important");
        settingsModal.style.setProperty("pointer-events", "auto", "important");
        setTimeout(() => {
            const firstFocusable = settingsModal.querySelector("button:not([disabled]), input:not([disabled]), select:not([disabled])");
            if (firstFocusable) firstFocusable.focus();
        }, 80);
    }

    function closeSettingsModal() {
        if (!settingsModal) return;
        // حماية ضد الإغلاق السريع الناتج عن النقرات الوهمية في شاشات اللمس والآي فريم
        if (Date.now() - modalOpenedAt < 350) return;
        settingsModal.classList.remove("is-open");
        settingsModal.style.setProperty("display", "none", "important");
        settingsModal.style.setProperty("visibility", "hidden", "important");
        settingsModal.style.setProperty("pointer-events", "none", "important");
    }

